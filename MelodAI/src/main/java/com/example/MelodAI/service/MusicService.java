package com.example.MelodAI.service;

import org.springframework.stereotype.Service;

import com.example.MelodAI.model.Credits;
import com.example.MelodAI.model.Music_Generated;
import com.example.MelodAI.repository.creditsRepository;
import com.example.MelodAI.repository.mus_genRepository;

import lombok.RequiredArgsConstructor;

@Service
@RequiredArgsConstructor
public class MusicService {

    private final mus_genRepository musGenRepository;
    private final creditsRepository creditsRepository;
    private final MusicGeneratorWorker musicGeneratorWorker;

    // @Transactional
    public Music_Generated musicGenerated(Long userId, String title){
        Credits userCredits = creditsRepository.findById(userId)
                .orElseThrow(() -> new RuntimeException("User credit profile not found."));

        if(userCredits.getCredits() <= 0){
            throw new RuntimeException("Insufficient credits! Please upgrade your account.");
        }
        userCredits.setCredits(userCredits.getCredits() - 1);
        creditsRepository.save(userCredits);

        Music_Generated track = new Music_Generated();
        track.setUser(userCredits.getUser());
        track.setTitle(title);
        track.setStatus("PENDING");

        Music_Generated savedTrack = musGenRepository.saveAndFlush(track);
        musicGeneratorWorker.generateMusicAsync(savedTrack.getId());

        return savedTrack;
    }

    // Get the status of a single track
    public Music_Generated getTrackStatus(Long trackId) {
        return musGenRepository.findById(trackId)
                .orElseThrow(() -> new RuntimeException("Track not found with ID: " + trackId));
    }

    // Get ALL tracks generated by a specific user (for their music library profile)
    public java.util.List<Music_Generated> getUserMusicLibrary(Long userId) {
        return musGenRepository.findByUser_Id(userId);
    }
}